for i in o:
    try:
        get_courier_handler(i.logistic_partner).cancel_shipment(i.awb_number)
        i.update_status("cancelled")
        trx_amount = i.payment.shipping_charges
        tr = Transaction.create_transaction(
            user=i.user,
            merchant_txn_id=str(i.id) + "_cancel_" + str(uuid.uuid4()),
            amount_rs=trx_amount,
            desc="cancelled_order",
            transaction_type="credit",
        )
        tr.credit(awb_number=i.awb_number)

        i.cancel_data[str(i.awb_number)] = {
            "cancelled_at": timezone.now().strftime("%Y-%m-%dT%H:%M:%SZ"),
            "courier": (
                f"{i.logistic_partner.name} ({i.logistic_partner.abbreviation})"
                if i.logistic_partner
                else "N/A"
            ),
            "refund_amount": i.payment.amount,
        }

        i.save()
        print(f"Done transaction for AWB: {i.awb_number}, Amount: {trx_amount}")
    except Exception as e:
        print(f"Error: {e}")

