def parse_delivery_date(date_str: str):
    """
    Parses ISO-8601 UTC timestamps like:
    2026-01-14T16:30:32Z
    """
    if not date_str:
        return None
    dt = datetime.strptime(date_str.strip(), "%Y-%m-%dT%H:%M:%SZ")
    return make_aware(dt, timezone=timezone.utc)


for order in orders:
    try:
        details = data.get(order.awb_number)
        if not details:
            continue
        old_status = order.status
        raw_status = details[0].strip()
        new_status = status_map.get(raw_status)
        if not new_status:
            print(f"Unknown status '{details[0]}' for AWB {order.awb_number}")
            continue
        if old_status != new_status:
            order.status = new_status
            order.save(update_fields=["status"])
        if new_status in ("delivered", "rto_delivered") and len(details) > 1:
            if order.shipment and details[1]:
                delivered_dt = parse_delivery_date(details[1])
                if delivered_dt:
                    order.shipment.delivered_at = delivered_dt
                    order.shipment.save(update_fields=["delivered_at"])
        print(
            f"Order {order.awb_number} status updated "
            f"from {old_status} to {new_status}"
        )
    except Exception as e:
        print(f"Error processing order {order.awb_number}: {e}")
        continue
